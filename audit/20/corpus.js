//   JS   src/<id>.js   = `'use strict';\n${pre}\n${cur}\n${rest}\n`
//        test/<id>.test.js requires `../src/<id>` as `m`; `test`/`assert` in scope.
//   Py   app/<id>.py   = `${pre}\n${cur}\n${rest}`
//        tests/test_<id>.py = `import app.<id> as m\n\n\n${test}`
//   tests: extra files (path -> content), e.g. a second test file.
//   pkg:   package.json fields (default scripts.test = 'node --test').
//   expect: 'stop' for controls whose evidence is meant to fail the bar.
//
// Categories
//   tmpl     JS: the change is inside a template literal `${...}`; the hunk's
//            only sites are on another token (a re-quoted string)
//   fstr     Python: the change is inside an f-string `{...}`; the only site
//            is the f-string itself (string_literal appends "x")
//   kwid     JS: an inserted read of `Infinity` (an identifier, not a keyword)
//   lit      literal spellings no operator applies to (hex, exponent,
//            separators, regex flags/classes) riding on a sibling site
//   modcall  an inserted module-function call (lowercase namespace): the
//            use-site mutant replaces the value by the module object
//   pertest  SG26 per-test kill: tests that fail on source text, duplicate
//            ids, parametrized ids, todo/xfail, tests that pass by throwing
//   use      SG26 use-site shapes (optional chaining, computed member,
//            closure, getter, default parameter, spread, walrus, keyword
//            argument, decorator, property)
//   pyconst  SG27 numeric-constant inputs (`module_nums`)
//   reporter SG28 reporter fallback: no per-test results, no kill

